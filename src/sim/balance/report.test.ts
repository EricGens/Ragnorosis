// Regenerates balance-report.md: `npm run balance`. Skipped in the normal test run (it stages a few
// tens of thousands of battles, a few minutes). The report is committed, so a tuning change shows up as a diff to it.

import { expect, it } from 'vitest'
import { designStats } from '../military/design'
import type { DesignInput } from '../military/roster'
import { forceCost, runBattle, runMatchup, type Battlefield, type Force } from './arena'
import { DESIGNS as D, mix, pure } from './forces'

const RUNS = 40
const BUDGET = 6000
const pct = (x: number) => `${Math.round(x * 100)}%`

function grid(title: string, forces: Force[], field: Battlefield = {}): string[] {
  const out = [`### ${title}`, '', 'Attacker win rate. Rows attack, columns defend.', '']
  out.push(`| attacker ↓ / defender → | ${forces.map((f) => f.name).join(' | ')} | average |`)
  out.push(`| --- | ${forces.map(() => '---:').join(' | ')} | ---: |`)
  for (const a of forces) {
    const rates = forces.map((b) => runMatchup(a, b, RUNS, field).attackerWinRate)
    out.push(
      `| **${a.name}** | ${rates.map(pct).join(' | ')} | ${pct(rates.reduce((s, r) => s + r, 0) / rates.length)} |`,
    )
  }
  return [...out, '']
}

function duel(a: Force, b: Force, field: Battlefield = {}): string {
  const m = runMatchup(a, b, RUNS, field)
  return `| ${a.name} | ${b.name} | ${pct(m.attackerWinRate)} | ${Math.round(m.meanTicks)} | ${pct(m.attackerLossShare)} | ${pct(m.defenderLossShare)} | ${pct(m.brokeShare)} |`
}
const DUEL_HEAD = [
  '| attacker | defender | attacker wins | ticks | attacker value lost | defender value lost | ended by Org break |',
  '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
]

it.runIf(import.meta.env.VITE_BALANCE)(
  'balance report',
  async () => {
    const out: string[] = [
      '# Balance report',
      '',
      'Generated by `npm run balance` — do not edit by hand. Every battle is a real invasion run through the',
      `game's combat code on plain ground (Defensibility 10, Stability 50), ${RUNS} seeds per matchup. Unless`,
      `noted, both sides have ${BUDGET} Production of filled units and the attacker arrives with Shock.`,
      '',
      '## Unit designs',
      '',
      '| design | cost | Manpower | Org | Health | Armor | Org per 100 Production | vector Inf/Veh/Tank/AA |',
      '| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
    ]
    for (const des of Object.values(D) as DesignInput[]) {
      const s = designStats(des.platform, des.modules)
      const vec = s.vector.map((e) => (e.long === null ? `${e.short}` : `${e.short}(${e.long})`)).join(' / ')
      out.push(
        `| ${des.name} | ${s.cost} | ${s.manpower} | ${s.organization} | ${s.health} | ${s.armor} | ${((s.organization / s.cost) * 100).toFixed(1)} | ${vec} |`,
      )
    }

    out.push('', '## Single-type forces', '')
    const singles = [D.lightInf, D.atInf, D.heavyInf, D.utility, D.recon, D.apc, D.ifv, D.mbt, D.mbtPlus].map((d) =>
      pure(BUDGET, d),
    )
    out.push(...grid(`Equal Production (${BUDGET})`, singles))

    out.push('## Mirror matches: what Shock is worth', '', ...DUEL_HEAD)
    for (const d of [D.atInf, D.recon, D.mbt]) {
      const f = pure(BUDGET, d)
      out.push(duel(f, f), duel(f, { ...f, name: `${f.name} (attacker has no Shock)` }, { shock: false }))
    }

    out.push('', '## Mass against quality as armies grow', '', 'AT Infantry against MBTs at equal Production.', '')
    out.push(...DUEL_HEAD)
    for (const budget of [600, 2400, 6000, 24000]) {
      const inf = { ...pure(budget, D.atInf), name: `AT Infantry ×${budget / 60}` }
      const mbt = { ...pure(budget, D.mbt), name: `MBT ×${budget / 200}` }
      out.push(duel(inf, mbt), duel(mbt, inf))
    }

    out.push('', '## Combined arms', '')
    const builds = (budget: number): Force[] => {
      const rest = (spent: number, unit: number) => Math.floor((budget - spent) / unit)
      return [
        mix('Infantry', [D.atInf, rest(0, 60)]),
        mix('Infantry + artillery', [D.atInf, rest(1200, 60)], [D.towed, 12]),
        mix('Infantry + artillery + CAS', [D.atInf, rest(2400, 60)], [D.towed, 12], [D.cas, 6]),
        mix('Tanks', [D.mbtPlus, rest(0, 220)]),
        mix('Tanks + artillery + CAS', [D.mbtPlus, rest(2400, 220)], [D.towed, 12], [D.cas, 6]),
        mix('12 tanks + Light Infantry', [D.mbtPlus, 12], [D.lightInf, rest(2640, 50)]),
        mix(
          '12 tanks + artillery + CAS + Light Infantry',
          [D.mbtPlus, 12],
          [D.towed, 12],
          [D.cas, 6],
          [D.lightInf, rest(5040, 50)],
        ),
      ]
    }
    for (const budget of [6000, 20000]) {
      const b = builds(budget)
      out.push(...grid(`Builds at ${budget} Production`, b))
      out.push(
        ...b.map(
          (f) =>
            `- ${f.name}: ${f.units.map(([d, n]) => `${n} ${d.name}`).join(', ')} — ${forceCost(f).manpower} Manpower`,
        ),
        '',
      )
    }

    out.push('## Does air defence blunt CAS?', '')
    out.push('Attacker: 60 AT Infantry + 6 CAS Aircraft, no Shock. Hit rate is per aircraft per tick.', '')
    out.push('| defender | CAS hit rate | aircraft shot down | attacker wins |', '| --- | ---: | ---: | ---: |')
    const striker = mix('strike', [D.atInf, 60], [D.cas, 6])
    for (const def of [
      mix('100 AT Infantry (no air defence)', [D.atInf, 100]),
      mix('94 AT Infantry + 6 AA Infantry in Reserves', [D.atInf, 94], [D.aaInf, 6]),
      mix('100 Heavy Infantry (air defence on every unit)', [D.heavyInf, 100]),
    ]) {
      let hits = 0
      let ticks = 0
      let shot = 0
      let wins = 0
      for (let seed = 1; seed <= RUNS; seed++) {
        const r = runBattle(striker, def, seed * 7919, { shock: false })
        hits += r.attacker.hits.cas
        ticks += r.ticks
        shot += r.defender.hits.airDefense
        if (r.attackerWon) wins++
      }
      out.push(
        `| ${def.name} | ${((hits / ticks / 6) * 100).toFixed(1)}% | ${(shot / RUNS).toFixed(1)} of 6 | ${pct(wins / RUNS)} |`,
      )
    }

    out.push('', '## Does the Front Line stay full, and how do battles end?', '')
    out.push(
      'Average Front Line slots filled (of 12) over the battle, and the share of battles the loser lost by',
      'running out of Organization rather than by having nothing left to hold the line.',
      '',
    )
    out.push(
      '| attacker | defender | attacker wins | attacker line | defender line | ended by Org break |',
      '| --- | --- | ---: | ---: | ---: | ---: |',
    )
    for (const [a, b] of [
      [pure(BUDGET, D.mbtPlus), pure(BUDGET, D.atInf)],
      [pure(BUDGET, D.atInf), pure(BUDGET, D.mbtPlus)],
      [pure(BUDGET, D.atInf), pure(BUDGET, D.atInf)],
      [pure(BUDGET, D.mbt), pure(BUDGET, D.mbt)],
      [mix('12 MBT+ only', [D.mbtPlus, 12]), pure(BUDGET, D.atInf)],
    ] as [Force, Force][]) {
      let wins = 0
      let la = 0
      let ld = 0
      let broke = 0
      for (let seed = 1; seed <= RUNS; seed++) {
        const r = runBattle(a, b, seed * 7919)
        if (r.attackerWon) wins++
        if (r.endReason === 'organization') broke++
        la += r.attacker.meanFrontLine
        ld += r.defender.meanFrontLine
      }
      out.push(
        `| ${a.name} | ${b.name} | ${pct(wins / RUNS)} | ${(la / RUNS).toFixed(1)} | ${(ld / RUNS).toFixed(1)} | ${pct(broke / RUNS)} |`,
      )
    }

    out.push('', '## What counters what: a base of infantry plus one purchase', '')
    out.push(
      'Both sides have the same infantry base and the same extra Production, and each spends the extra on one',
      "thing. Each cell is the row force's result against the column force, averaged over attacking it and",
      'defending against it (50% = even). Tanks and vehicles are placed on the Front Line ahead of the base;',
      'air-defence units wait in Reserves, where they intercept CAS.',
      '',
    )
    const count = (budget: number, d: DesignInput) => Math.floor(budget / designStats(d.platform, d.modules).cost)
    type Purchase = {
      name: string
      build: (base: DesignInput, baseN: number, extra: number) => [DesignInput, number][]
    }
    const ahead = (name: string, d: DesignInput): Purchase => ({
      name,
      build: (base, k, x) => [
        [d, count(x, d)],
        [base, k],
      ],
    })
    const behind = (name: string, d: DesignInput): Purchase => ({
      name,
      build: (base, k, x) => [
        [base, k],
        [d, count(x, d)],
      ],
    })
    const purchases: Purchase[] = [
      { name: 'More infantry', build: (base, k, x) => [[base, k + count(x, base)]] },
      behind('AA Infantry', D.aaInf),
      ahead('Recon Vehicles', D.recon),
      behind('SHORAD Vehicles', D.shorad),
      ahead('IFVs', D.ifv),
      ahead('MBT+', D.mbtPlus),
      ahead('MBT (AT)', D.mbtAT),
      behind('Towed Artillery', D.towed),
      behind('MLRS', D.mlrs),
      behind('CAS', D.cas),
      {
        name: 'Spread',
        build: (base, k, x) => [
          [D.mbtPlus, count(x / 3, D.mbtPlus)],
          [base, k],
          [D.towed, count(x / 3, D.towed)],
          [D.cas, count(x / 3, D.cas)],
        ],
      },
    ]
    for (const [base, baseN, extra] of [
      [D.lightInf, 40, 1200],
      [D.atInf, 40, 1200],
      [D.atInf, 100, 2400],
    ] as const) {
      const forces = purchases.map((p) => mix(p.name, ...p.build(base, baseN, extra)))
      const wins = forces.map((a) => forces.map((b) => runMatchup(a, b, 30).attackerWinRate))
      out.push(`### Base: ${baseN} ${base.name}, plus ${extra} Production`, '')
      out.push(
        `| you ↓ / opponent → | ${forces.map((f) => f.name).join(' | ')} | average |`,
        `| --- | ${forces.map(() => '---:').join(' | ')} | ---: |`,
      )
      forces.forEach((f, i) => {
        const row = forces.map((_, j) => (wins[i][j] + (1 - wins[j][i])) / 2)
        out.push(
          `| **${f.name}** | ${row.map(pct).join(' | ')} | ${pct(row.reduce((s, v) => s + v, 0) / row.length)} |`,
        )
      })
      out.push('', ...forces.map((f) => `- ${f.name}: ${f.units.map(([d, k]) => `${k} ${d.name}`).join(' + ')}`), '')
    }

    out.push('## Holding ground: a poorer infantry force on defensible terrain', '')
    out.push(
      'How often a defender with 3,000 Production holds against a richer combined-arms attacker, by terrain.',
      "Defensibility strengthens the defender's Front Line and, through cover, absorbs part of the",
      "attacker's CAS hits and artillery strikes.",
      '',
    )
    const terrains: [string, Battlefield][] = [
      ['plain (10)', {}],
      ['Fortification 5 (35)', { fortification: 5 }],
      ['Fortification 10, rugged, mountainous (80)', { fortification: 10, traits: ['rugged', 'mountainous'] }],
    ]
    const richInfantry = mix(
      '4,500: 35 AT Infantry + 12 Towed Artillery + 6 CAS',
      [D.atInf, 35],
      [D.towed, 12],
      [D.cas, 6],
    )
    const richArmour = mix(
      '6,000: 12 MBT+ + 12 Towed Artillery + 6 CAS + 16 AT Infantry',
      [D.mbtPlus, 12],
      [D.towed, 12],
      [D.cas, 6],
      [D.atInf, 16],
    )
    out.push(
      `| defender (3,000) | attacker | ${terrains.map((t) => t[0]).join(' | ')} |`,
      `| --- | --- | ${terrains.map(() => '---:').join(' | ')} |`,
    )
    for (const def of [
      mix('50 AT Infantry', [D.atInf, 50]),
      mix('30 AT Infantry + 12 Towed Artillery', [D.atInf, 30], [D.towed, 12]),
    ])
      for (const atk of [richInfantry, richArmour])
        out.push(
          `| ${def.name} | ${atk.name} | ${terrains.map(([, f]) => pct(1 - runMatchup(atk, def, RUNS, f).attackerWinRate)).join(' | ')} |`,
        )
    out.push('')

    out.push('', '## Is there a win button?', '')
    out.push(
      'The three strongest attackers against every defending composition in a search space of fronts',
      '(infantry or 12–24 tanks), artillery, CAS and Reserve fillers. Listed: the defenders whose *worst* result',
      'is best — hold rate against each attacker. If nothing here holds, the attackers have no counter.',
      '',
    )
    for (const budget of [6000, 20000]) {
      const attackers = builds(budget).filter(
        (f) => f.name.includes('artillery + CAS') && f.name !== 'Infantry + artillery + CAS',
      )
      const attackersAll = [...attackers, builds(budget)[2]]
      const cost = (d: DesignInput) => designStats(d.platform, d.modules).cost
      const found: { name: string; hold: number[] }[] = []
      const fronts: [DesignInput, number | null][] = [
        [D.atInf, null],
        [D.heavyInf, null],
        [D.mbtPlus, 12],
        [D.mbtAT, 12],
        [D.mbtPlus, 24],
        [D.mbtAT, 24],
      ]
      for (const [front, count] of fronts)
        for (const arty of [null, D.towed, D.mlrs])
          for (const cas of [0, 6])
            for (const filler of [D.lightInf, D.atInf, D.heavyInf]) {
              if (count === null && filler !== front) continue
              const units: [DesignInput, number][] = []
              if (count !== null) units.push([front, count])
              if (arty) units.push([arty, 12])
              if (cas) units.push([D.cas, cas])
              const spent = units.reduce((s, [d, n]) => s + n * cost(d), 0)
              const n = Math.floor((budget - spent) / cost(filler))
              if (n < 0) continue
              if (n > 0) units.push([filler, n])
              const def = mix(units.map(([d, k]) => `${k} ${d.name}`).join(' + '), ...units)
              found.push({ name: def.name, hold: attackersAll.map((a) => 1 - runMatchup(a, def, 16).attackerWinRate) })
            }
      found.sort(
        (x, y) =>
          Math.min(...y.hold) - Math.min(...x.hold) ||
          y.hold.reduce((s, v) => s + v, 0) - x.hold.reduce((s, v) => s + v, 0),
      )
      out.push(`### ${budget} Production (${found.length} defenders tried)`, '')
      out.push(
        `| defender | ${attackersAll.map((a) => `holds vs ${a.name}`).join(' | ')} |`,
        `| --- | ${attackersAll.map(() => '---:').join(' | ')} |`,
      )
      for (const f of found.slice(0, 5)) out.push(`| ${f.name} | ${f.hold.map(pct).join(' | ')} |`)
      out.push('')
    }

    await expect(out.join('\n') + '\n').toMatchFileSnapshot('./balance-report.md')
  },
  600_000,
)
