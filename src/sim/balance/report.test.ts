// Regenerates balance-report.md: `npm run balance`. Skipped in the normal test run (it stages a few
// thousand battles, about 40 seconds). The report is committed, so a tuning change shows up as a diff to it.

import { expect, it } from 'vitest'
import { designStats } from '../military/design'
import type { DesignInput } from '../military/roster'
import { forceCost, runBattle, runMatchup, type Battlefield, type Force } from './arena'
import { DESIGNS as D, mix, pure } from './forces'

const RUNS = 40
const BUDGET = 6000
const pct = (x: number) => `${Math.round(x * 100)}%`

function grid(title: string, forces: Force[], field: Battlefield = {}): string[] {
  const out = [`### ${title}`, '', 'Attacker win rate. Rows attack, columns defend.', '']
  out.push(`| attacker ↓ / defender → | ${forces.map((f) => f.name).join(' | ')} | average |`)
  out.push(`| --- | ${forces.map(() => '---:').join(' | ')} | ---: |`)
  for (const a of forces) {
    const rates = forces.map((b) => runMatchup(a, b, RUNS, field).attackerWinRate)
    out.push(
      `| **${a.name}** | ${rates.map(pct).join(' | ')} | ${pct(rates.reduce((s, r) => s + r, 0) / rates.length)} |`,
    )
  }
  return [...out, '']
}

function duel(a: Force, b: Force, field: Battlefield = {}): string {
  const m = runMatchup(a, b, RUNS, field)
  return `| ${a.name} | ${b.name} | ${pct(m.attackerWinRate)} | ${Math.round(m.meanTicks)} | ${pct(m.attackerLossShare)} | ${pct(m.defenderLossShare)} | ${pct(m.brokeShare)} |`
}
const DUEL_HEAD = [
  '| attacker | defender | attacker wins | ticks | attacker value lost | defender value lost | ended by Org break |',
  '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
]

it.runIf(import.meta.env.VITE_BALANCE)(
  'balance report',
  async () => {
    const out: string[] = [
      '# Balance report',
      '',
      'Generated by `npm run balance` — do not edit by hand. Every battle is a real invasion run through the',
      `game's combat code on plain ground (Defensibility 10, Stability 50), ${RUNS} seeds per matchup. Unless`,
      `noted, both sides have ${BUDGET} Production of filled units and the attacker arrives with Shock.`,
      '',
      '## Unit designs',
      '',
      '| design | cost | Manpower | Org | Health | Armor | Org per 100 Production | vector Inf/Veh/Tank/AA |',
      '| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
    ]
    for (const des of Object.values(D) as DesignInput[]) {
      const s = designStats(des.platform, des.modules)
      const vec = s.vector.map((e) => (e.long === null ? `${e.short}` : `${e.short}(${e.long})`)).join(' / ')
      out.push(
        `| ${des.name} | ${s.cost} | ${s.manpower} | ${s.organization} | ${s.health} | ${s.armor} | ${((s.organization / s.cost) * 100).toFixed(1)} | ${vec} |`,
      )
    }

    out.push('', '## Single-type forces', '')
    const singles = [D.lightInf, D.atInf, D.heavyInf, D.utility, D.recon, D.apc, D.ifv, D.mbt, D.mbtPlus].map((d) =>
      pure(BUDGET, d),
    )
    out.push(...grid(`Equal Production (${BUDGET})`, singles))

    out.push('## Mirror matches: what Shock is worth', '', ...DUEL_HEAD)
    for (const d of [D.atInf, D.recon, D.mbt]) {
      const f = pure(BUDGET, d)
      out.push(duel(f, f), duel(f, { ...f, name: `${f.name} (attacker has no Shock)` }, { shock: false }))
    }

    out.push('', '## Mass against quality as armies grow', '', 'AT Infantry against MBTs at equal Production.', '')
    out.push(...DUEL_HEAD)
    for (const budget of [600, 2400, 6000, 24000]) {
      const inf = { ...pure(budget, D.atInf), name: `AT Infantry ×${budget / 60}` }
      const mbt = { ...pure(budget, D.mbt), name: `MBT ×${budget / 200}` }
      out.push(duel(inf, mbt), duel(mbt, inf))
    }

    out.push('', '## Combined arms', '')
    const builds = (budget: number): Force[] => {
      const rest = (spent: number, unit: number) => Math.floor((budget - spent) / unit)
      return [
        mix('Infantry', [D.atInf, rest(0, 60)]),
        mix('Infantry + artillery', [D.atInf, rest(1200, 60)], [D.towed, 12]),
        mix('Infantry + artillery + CAS', [D.atInf, rest(2400, 60)], [D.towed, 12], [D.cas, 6]),
        mix('Tanks', [D.mbtPlus, rest(0, 220)]),
        mix('Tanks + artillery + CAS', [D.mbtPlus, rest(2400, 220)], [D.towed, 12], [D.cas, 6]),
        mix('12 tanks + Light Infantry', [D.mbtPlus, 12], [D.lightInf, rest(2640, 50)]),
        mix(
          '12 tanks + artillery + CAS + Light Infantry',
          [D.mbtPlus, 12],
          [D.towed, 12],
          [D.cas, 6],
          [D.lightInf, rest(5040, 50)],
        ),
      ]
    }
    for (const budget of [6000, 20000]) {
      const b = builds(budget)
      out.push(...grid(`Builds at ${budget} Production`, b))
      out.push(
        ...b.map(
          (f) =>
            `- ${f.name}: ${f.units.map(([d, n]) => `${n} ${d.name}`).join(', ')} — ${forceCost(f).manpower} Manpower`,
        ),
        '',
      )
    }

    out.push('## Does air defence blunt CAS?', '')
    out.push('Attacker: 60 AT Infantry + 6 CAS Aircraft, no Shock. Hit rate is per aircraft per tick.', '')
    out.push('| defender | CAS hit rate | aircraft shot down | attacker wins |', '| --- | ---: | ---: | ---: |')
    const striker = mix('strike', [D.atInf, 60], [D.cas, 6])
    for (const def of [
      mix('100 AT Infantry (no air defence)', [D.atInf, 100]),
      mix('94 AT Infantry + 6 AA Infantry in Reserves', [D.atInf, 94], [D.aaInf, 6]),
      mix('100 Heavy Infantry (air defence on every unit)', [D.heavyInf, 100]),
    ]) {
      let hits = 0
      let ticks = 0
      let shot = 0
      let wins = 0
      for (let seed = 1; seed <= RUNS; seed++) {
        const r = runBattle(striker, def, seed * 7919, { shock: false })
        hits += r.attacker.hits.cas
        ticks += r.ticks
        shot += r.defender.hits.airDefense
        if (r.attackerWon) wins++
      }
      out.push(
        `| ${def.name} | ${((hits / ticks / 6) * 100).toFixed(1)}% | ${(shot / RUNS).toFixed(1)} of 6 | ${pct(wins / RUNS)} |`,
      )
    }

    await expect(out.join('\n') + '\n').toMatchFileSnapshot('./balance-report.md')
  },
  600_000,
)
